#!/usr/bin/env node
// Generates src/cli-commands.ts from the typed API modules so the CLI can
// expose every namespace method as a subcommand. Re-run after adding methods:
//   node scripts/gen-cli-commands.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = join(here, "..", "src", "api");
const outFile = join(here, "..", "src", "cli-commands.ts");

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`).replace(/^-/, "");
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const files = readdirSync(apiDir).filter((f) => f.endsWith(".ts")).sort();
const commands = [];

for (const file of files) {
  const namespace = camel(file.replace(/\.ts$/, "")); // matches client accessor name
  const text = readFileSync(join(apiDir, file), "utf8");

  // Locate every method declaration at 2-space indent: `  name<...` or `  name(`.
  const declRe = /\n {2}([a-z][A-Za-z0-9]*)\s*[<(]/g;
  const decls = [];
  let m;
  while ((m = declRe.exec(text))) decls.push({ name: m[1], index: m.index });

  for (let i = 0; i < decls.length; i += 1) {
    const start = decls[i].index;
    const end = i + 1 < decls.length ? decls[i + 1].index : text.length;
    const block = text.slice(start, end);

    // The HTTP call: this.http.<verb><T>("path" | `path`, ...)
    const call = block.match(
      /this\.http\.(get|post|put|patch|delete)<[^>]*>\(\s*(`[^`]*`|"[^"]*")/,
    );
    if (!call) continue;
    const verb = call[1].toUpperCase();
    const rawPath = call[2];

    // Ordered path params from ${encodeURIComponent(name)} occurrences.
    const pathParams = [];
    const encRe = /\$\{encodeURIComponent\(([A-Za-z0-9_]+)\)\}/g;
    let e;
    while ((e = encRe.exec(rawPath))) pathParams.push(e[1]);

    // Display path: strip template interpolation into :param form.
    const path = rawPath
      .slice(1, -1)
      .replace(/\$\{encodeURIComponent\(([A-Za-z0-9_]+)\)\}/g, ":$1")
      .replace(/\$\{[^}]*\}/g, ":param");

    // Ordered parameter list (name + role), excluding the trailing `options`.
    const sigStart = block.indexOf("(");
    const sigEnd = block.indexOf("): Promise");
    const paramSrc = sigStart >= 0 && sigEnd > sigStart ? block.slice(sigStart + 1, sigEnd) : "";
    const params = [];
    const paramRe = /(?:^|[,(])\s*([A-Za-z_][A-Za-z0-9_]*)\??:/g;
    let p;
    while ((p = paramRe.exec(paramSrc))) {
      const name = p[1];
      if (name === "options") continue;
      const role = name === "body" ? "body" : name === "query" ? "query" : "positional";
      params.push({ name, role });
    }
    const hasBody = params.some((x) => x.role === "body");
    const hasQuery = params.some((x) => x.role === "query");
    const nonEnvelope = /unwrapEnvelope:\s*false/.test(block);

    commands.push({
      namespace,
      command: kebab(decls[i].name),
      method: decls[i].name,
      verb,
      path,
      pathParams,
      params,
      hasBody,
      hasQuery,
      nonEnvelope,
    });
  }
}

commands.sort((a, b) =>
  a.namespace === b.namespace
    ? a.command.localeCompare(b.command)
    : a.namespace.localeCompare(b.namespace),
);

const header = `// AUTO-GENERATED by scripts/gen-cli-commands.mjs — do not edit by hand.
// Describes every namespace method so the CLI can dispatch and self-document.

export type CliParamRole = "positional" | "body" | "query";

export interface CliParam {
  name: string;
  role: CliParamRole;
}

export interface CliCommand {
  namespace: string;
  command: string;
  method: string;
  verb: string;
  path: string;
  pathParams: string[];
  params: CliParam[];
  hasBody: boolean;
  hasQuery: boolean;
  nonEnvelope: boolean;
}

export const COMMANDS: readonly CliCommand[] = ${JSON.stringify(commands, null, 2)};
`;

writeFileSync(outFile, header);
console.log(`Wrote ${commands.length} commands across ${new Set(commands.map((c) => c.namespace)).size} namespaces to ${outFile}`);
